def num(v, digits=4):
    if isinstance(v, str):
        try:
            v = float(v)
        except ValueError:
            return v
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    if v == 0:
        return "0"
    a = abs(v)
    if a >= 1e5 or a < 1e-3:
        m, e = f"{v:.{digits - 1}e}".split("e")
        return f"${m}\\times10^{{{int(e)}}}$"
    d = max(0, digits - 1 - int(math.floor(math.log10(a))))
    s = f"{v:.{d}f}".rstrip("0").rstrip(".")
    if a >= 1000:
        s = f"{v:,.0f}"
    return s


def write_table(path, caption, label, colspec, header, rows, note):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(BANNER.format(d=date.today().isoformat()))
        f.write("\\begin{table}[!htb]\n\\centering\n\\begin{threeparttable}\n")
        f.write(f"\\caption{{{caption}}}\\label{{{label}}}\n")
        f.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{header} \\\\\n\\midrule\n")
        for r in rows:
            f.write(r + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
        f.write("\\begin{tablenotes}[flushleft]\n\\footnotesize\n")
        f.write(f"\\item[] \\textit{{Note:}} {note}\n\\end{{tablenotes}}\n")
        f.write("\\end{threeparttable}\n\\end{table}\n")
    return path


def load(block):
    d = pd.read_csv(os.path.join(PROCESSED, block + ".csv"))
    return OrderedDict((r["name"], r) for _, r in d.iterrows())


def block_table(fname, caption, label, block, spec, note, unit_col=True):
    """spec: list of (csv name, printed label) or ("--", section heading)."""
    d = load(block)
    rows = []
    for name, text in spec:
        if name == "--":
            rows.append(f"\\multicolumn{{{3 if unit_col else 2}}}{{l}}{{\\emph{{{text}}}}}")
            continue
        r = d[name]
        unit = str(r["unit"]).replace("%", "\\%").replace("$", "\\$").replace("_", "\\_").replace("^", "\\^{}")
        cells = [text, num(r["value"])] + ([unit] if unit_col else [])
        rows.append(" & ".join(cells))
    return write_table(os.path.join(TABLES, fname), caption, label,
                       "lr" + ("l" if unit_col else ""), "Quantity & Value" + (" & Unit" if unit_col else ""),
                       rows, note)


